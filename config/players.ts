/**
 * Native-script name: Wikidata lookups (config/ja-names.json, generated by
 * `npm run ja-names`) win; the hand-written map above is the fallback.
 */
export function japaneseName(id: number, name: string): string | null {
  const fromWikidata = (WIKIDATA as Record<string, string>)[String(id)];
  if (fromWikidata) return fromWikidata;
  const key = name
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim();
  return JA_NAMES[key]?.replace(/ /g, "") ?? null;
}
